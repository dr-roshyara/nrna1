print(" Rec_3 lam-=0 (tau_dom default (1,2,3)):",rec(E,3,("valid","e"),th(),100,0,0),
      "| worlds:",len(worlds(E,3,th(),(1,2,3),("p1","p2"))))
print(" Rec_3 lam-=0 with tau_dom (1..7):",rec(E,3,("valid","e"),th(),100,0,0,tau_dom=tuple(range(1,8))))
